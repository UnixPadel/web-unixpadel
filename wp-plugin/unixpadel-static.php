/** One trimmed, sanitized, length-capped field from the request. */
function upx_quote_field($params, $key, $max) {
	$value = isset($params[$key]) && is_scalar($params[$key]) ? (string) $params[$key] : '';
	$value = $key === 'message' ? sanitize_textarea_field($value) : sanitize_text_field($value);
	return function_exists('mb_substr') ? mb_substr($value, 0, $max) : substr($value, 0, $max);
}

function upx_quote_submit(WP_REST_Request $request) {
	$params = $request->get_json_params();
	if (!is_array($params)) {
		$params = $request->get_body_params();
	}

	// Bots: honeypot filled or the form sent faster than a person can type. Answer "ok" so they move on.
	$elapsed = isset($params['elapsed']) ? (int) $params['elapsed'] : 0;
	if (!empty($params['website']) || $elapsed < UPX_QUOTE_MIN_MS) {
		return new WP_REST_Response(array('ok' => true), 200);
	}

	$ip   = isset($_SERVER['REMOTE_ADDR']) ? (string) $_SERVER['REMOTE_ADDR'] : '';
	$key  = 'upx_quote_' . md5($ip);
	$hits = (int) get_transient($key);
	if ($hits >= UPX_QUOTE_MAX_PER_IP) {
		return new WP_REST_Response(array('ok' => false, 'error' => 'rate_limited'), 429);
	}
	set_transient($key, $hits + 1, UPX_QUOTE_WINDOW);

	$f = array(
		'name'        => upx_quote_field($params, 'name', 100),
		'company'     => upx_quote_field($params, 'company', 150),
		'email'       => sanitize_email(upx_quote_field($params, 'email', 254)),
		'phone'       => upx_quote_field($params, 'phone', 40),
		'country'     => upx_quote_field($params, 'country', 80),
		'projectType' => upx_quote_field($params, 'projectType', 80),
		'product'     => upx_quote_field($params, 'product', 150),
		'courts'      => upx_quote_field($params, 'courts', 4),
		'message'     => upx_quote_field($params, 'message', 5000),
		'lang'        => upx_quote_field($params, 'lang', 5),
		'page'        => esc_url_raw(upx_quote_field($params, 'page', 300)),
	);
	$invalid = array();
	if (strlen($f['name']) < 2) {
		$invalid[] = 'name';
	}
	if (!is_email($f['email'])) {
		$invalid[] = 'email';
	}
	if (strlen($f['country']) < 2) {
		$invalid[] = 'country';
	}
	if (empty($params['consent'])) {
		$invalid[] = 'consent';
	}
	if ($invalid) {
		return new WP_REST_Response(array('ok' => false, 'error' => 'invalid', 'fields' => $invalid), 400);
	}

	$rows = array(
		'Name'           => $f['name'],
		'Company / club' => $f['company'],
		'Email'          => $f['email'],
		'Phone'          => $f['phone'],
		'Country'        => $f['country'],
		'Project type'   => $f['projectType'],
		'Court / system' => $f['product'],
		'Courts'         => $f['courts'],
		'Language'       => $f['lang'],
		'Sent from'      => $f['page'],
	);
	$body = '';
	foreach ($rows as $label => $value) {
		if ($value !== '') {
			$body .= $label . ': ' . $value . "\n";
		}
	}
	if ($f['message'] !== '') {
		$body .= "\nProject details:\n" . $f['message'] . "\n";
	}

	$subject = sprintf('Quote request: %s (%s)', $f['name'], $f['country']);
	$reply   = str_replace(array('"', '<', '>', ',', ';'), '', $f['name']);
	$headers = array(
		'Content-Type: text/plain; charset=UTF-8',
		sprintf('Reply-To: "%s" <%s>', $reply, $f['email']),
	);
	$intro = "THIS MESSAGE COMES FROM THE QUOTE REQUEST FORM ON THE UNIXPADEL WEBSITE (unixpadel.com).\n"
		. sprintf("A potential customer asked for a quote. Reply to this email to answer %s directly.\n", $f['email'])
		. str_repeat('=', 64) . "\n\n";
	$mailed = wp_mail(
		upx_quote_to(),
		'[Unixpadel Website] New quote request from the website form: ' . $f['name'] . ' (' . $f['country'] . ')',
		$intro . $body . "\n--\nSent automatically by the quote request form on unixpadel.com. Also saved in WordPress → Quote requests.\n",
		$headers
	);

	$saved = wp_insert_post(array(
		'post_type'    => UPX_QUOTE_POST_TYPE,
		'post_status'  => 'private',
		'post_title'   => $subject . ($mailed ? '' : ' [email not sent]'),
		'post_content' => $body,
	), true);

	if (!$mailed && is_wp_error($saved)) {
		return new WP_REST_Response(array('ok' => false, 'error' => 'not_delivered'), 500);
	}
	return new WP_REST_Response(array('ok' => true), 200);
}

/* ---------- Activation ---------- */

function upx_activate() {
	add_option(UPX_OPT_MODE, 'preview'); // add_option never overwrites: updates keep the chosen mode
	upx_token();
}
register_activation_hook(__FILE__, 'upx_activate');

function upx_uninstall() {
	delete_option(UPX_OPT_MODE);
	delete_option(UPX_OPT_TOKEN);
	delete_option(UPX_OPT_QUOTE_TO); // saved quote requests stay (Quote requests → Trash to remove them)
	delete_option(UPX_OPT_QUOTE_TO_LEGACY);
	delete_option(UPX_OPT_REFS);     // references stay as posts; the index is rebuilt when the plugin comes back
	foreach (array(UPX_OPT_GH_REPO, UPX_OPT_GH_TOKEN, UPX_OPT_DEPLOY_SECRET, UPX_OPT_DEPLOY_AUTO, UPX_OPT_DEPLOY_LOG, UPX_OPT_DEPLOY_PREVIOUS) as $option) {
		delete_option($option);
	}
	wp_clear_scheduled_hook(UPX_DEPLOY_CRON);
}
register_uninstall_hook(__FILE__, 'upx_uninstall');

