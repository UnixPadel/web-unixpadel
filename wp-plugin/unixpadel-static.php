function upx_refs_rebuild_action() {
	if (!current_user_can('manage_options')) {
		wp_die('Not allowed.', 403);
	}
	check_admin_referer('upx_refs_rebuild');
	upx_refs_rebuild();
	upx_purge_page_caches();
	wp_safe_redirect(admin_url('options-general.php?page=unixpadel-static&upx_rebuilt=1'));
	exit;
}
add_action('admin_post_upx_refs_rebuild', 'upx_refs_rebuild_action');

