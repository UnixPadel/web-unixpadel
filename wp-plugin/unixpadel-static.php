function upx_register_setting() {
	register_setting('upx_static', UPX_OPT_MODE, array(
		'type'              => 'string',
		'default'           => 'preview',
		'sanitize_callback' => function ($value) {
			return in_array($value, array('off', 'preview', 'live'), true) ? $value : 'preview';
		},
	));
	register_setting('upx_static', UPX_OPT_QUOTE_TO, array(
		'type'              => 'string',
		'default'           => UPX_QUOTE_TO_DEFAULT,
		'sanitize_callback' => function ($value) {
			$emails = upx_parse_emails($value);
			return $emails ? implode(', ', $emails) : UPX_QUOTE_TO_DEFAULT;
		},
	));
}
add_action('admin_init', 'upx_register_setting');

