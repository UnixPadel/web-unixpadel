/**
 * Pure routing decision (no WordPress calls), so it can be tested on its own.
 *
 * @param string $path      URL path, already decoded, without query string.
 * @param string $dist      Absolute path of the bundled dist folder.
 * @param array  $redirects Map of old path => new path (both with leading and trailing slash).
 * @return array            ['pass'] | ['redirect', $target] | ['file', $file, $content_type] | ['notfound']
 */
function upx_resolve($path, $dist, $redirects) {
	if (!is_string($path) || $path === '' || $path[0] !== '/' || strpos($path, "\0") !== false) {
		return array('pass');
	}
	if (preg_match(UPX_PASS_PREFIX, $path)) {
		return array('pass');
	}
	if (preg_match(UPX_SHELL_PATH, $path)) {
		return array('notfound');
	}
	if (array_key_exists($path, UPX_ROOT_FILES)) {
		$file = $dist . $path;
		return is_file($file) ? array('file', $file, UPX_ROOT_FILES[$path]) : array('pass');
	}
	if (in_array($path, UPX_YOAST_SITEMAPS, true)) {
		return is_file($dist . '/sitemap-index.xml') ? array('redirect', '/sitemap-index.xml') : array('pass');
	}

	$slashed = substr($path, -1) === '/' ? $path : $path . '/';
	// Only plain slug segments: rules out "..", file extensions (robots.txt, wp-login.php, favicon.ico) and odd input.
	if (!preg_match('#^(/[A-Za-z0-9_-]+)*/$#', $slashed)) {
		return array('pass');
	}
	if (isset($redirects[$slashed])) {
		return array('redirect', $redirects[$slashed]);
	}
	$file = $dist . $slashed . 'index.html';
	if (!is_file($file)) {
		return array('pass'); // not part of the new site: WordPress keeps answering it
	}
	if ($slashed !== $path) {
		return array('redirect', $slashed);
	}
	return array('file', $file, 'text/html; charset=utf-8');
}

function upx_redirects() {
	static $map = null;
	if ($map === null) {
		$file = __DIR__ . '/redirects.php';
		$map  = is_file($file) ? (require $file) : array();
		$map  = is_array($map) ? $map : array();
	}
	return $map;
}

function upx_mode() {
	$mode = get_option(UPX_OPT_MODE, 'preview');
	return in_array($mode, array('off', 'preview', 'live'), true) ? $mode : 'preview';
}

function upx_token() {
	$token = get_option(UPX_OPT_TOKEN);
	if (!$token) {
		$token = wp_generate_password(20, false);
		update_option(UPX_OPT_TOKEN, $token, false);
	}
	return $token;
}

function upx_preview_url() {
	return add_query_arg(UPX_COOKIE, upx_token(), home_url('/'));
}

/** Who sees the new site right now. */
function upx_is_active_for_request() {
	$mode = upx_mode();
	if ($mode === 'live') {
		return true;
	}
	if ($mode !== 'preview') {
		return false;
	}
	if (current_user_can('manage_options')) {
		return true;
	}
	return isset($_COOKIE[UPX_COOKIE]) && hash_equals(upx_token(), (string) $_COOKIE[UPX_COOKIE]);
}

/** ?upx_preview=<token> turns preview on for this browser, ?upx_preview=0 turns it off. */
function upx_handle_preview_param() {
	if (!isset($_GET[UPX_COOKIE]) || upx_mode() !== 'preview') {
		return;
	}
	$value  = (string) wp_unslash($_GET[UPX_COOKIE]);
	$path   = defined('COOKIEPATH') && COOKIEPATH ? COOKIEPATH : '/';
	$domain = defined('COOKIE_DOMAIN') ? COOKIE_DOMAIN : '';
	if (hash_equals(upx_token(), $value)) {
		setcookie(UPX_COOKIE, $value, time() + 7 * DAY_IN_SECONDS, $path, $domain, is_ssl(), true);
		$_COOKIE[UPX_COOKIE] = $value;
	} elseif ($value === '0') {
		setcookie(UPX_COOKIE, '', time() - HOUR_IN_SECONDS, $path, $domain, is_ssl(), true);
		unset($_COOKIE[UPX_COOKIE]);
	} else {
		return;
	}
	nocache_headers();
	wp_redirect(remove_query_arg(UPX_COOKIE), 302, 'Unixpadel Static');
	exit;
}

function upx_maybe_serve() {
	if (is_admin() || wp_doing_ajax() || wp_doing_cron() || (defined('WP_CLI') && WP_CLI)) {
		return;
	}
	$method = isset($_SERVER['REQUEST_METHOD']) ? strtoupper($_SERVER['REQUEST_METHOD']) : 'GET';
	if ($method !== 'GET' && $method !== 'HEAD') {
		return;
	}
	upx_handle_preview_param();
	// Reference previews for editors (WP admin → References → Pages and preview), in any mode but off.
	if (isset($_GET['upx_ref_preview']) && upx_mode() !== 'off') {
		$lang = isset($_GET['upx_lang']) ? sanitize_key(wp_unslash($_GET['upx_lang'])) : 'en';
		$html = upx_ref_preview_html(absint($_GET['upx_ref_preview']), $lang);
		if ($html !== null) {
			nocache_headers();
			upx_send_body($html, 'text/html; charset=utf-8', 200, true, $method, time());
		}
	}
	if (!upx_is_active_for_request()) {
		return;
	}
	foreach (UPX_PASS_QUERY as $key) {
		if (isset($_GET[$key])) {
			return;
		}
	}

	$uri  = UPX_REQUEST_URI;
	$path = rawurldecode((string) parse_url($uri, PHP_URL_PATH));
	// Built references imported into WP admin are answered by their WP admin copy, before the build's own page.
	$hit  = upx_refs_safe('upx_refs_intercept', array($path));
	$hit  = $hit !== null ? $hit : upx_resolve($path, UPX_DIST, upx_redirects());
	if ($hit[0] === 'pass') {
		// Not in the build: maybe a reference written in WP admin (or its sitemap).
		$hit = upx_refs_safe('upx_refs_route', array($path));
		if ($hit === null) {
			return;
		}
	}

	$preview = upx_mode() !== 'live';
	if ($preview) {
		nocache_headers(); // keep page caches from storing the preview for everyone
	}

	if ($hit[0] === 'redirect') {
		$query = (string) parse_url($uri, PHP_URL_QUERY);
		wp_redirect($hit[1] . ($query !== '' ? '?' . $query : ''), 301, 'Unixpadel Static');
		exit;
	}
	if ($hit[0] === 'notfound') {
		// Reference shells, and references without a page in this language: the site's 404 page, without asking
		// WordPress (whose rewrite rules can answer deep unknown paths with the blog index).
		upx_send_file(upx_404_file($path), 'text/html; charset=utf-8', 404, $preview, $method);
	}
	if ($hit[0] === 'body') {
		upx_send_body($hit[1], $hit[2], 200, $preview, $method, $hit[3]);
	}

	// Hub, home, sitemap index and llms.txt list the WP admin references too.
	$body = upx_refs_safe('upx_refs_filter_file', array($path, $hit[1]));
	if ($body !== null) {
		upx_send_body($body, $hit[2], 200, $preview, $method, max((int) filemtime($hit[1]), (int) upx_refs_index()['version']));
	}
	upx_send_file($hit[1], $hit[2], 200, $preview, $method);
}
add_action('init', 'upx_maybe_serve', 0);

/** Calls a references function; an error in it never takes the site down (logged, then the request goes on as if it returned null). */
function upx_refs_safe($fn, $args) {
	try {
		return call_user_func_array($fn, $args);
	} catch (Throwable $e) {
		error_log('Unixpadel references: ' . $e->getMessage());
		return null;
	}
}

/** Sends a dist file and exits. Live responses carry validators so crawlers can revalidate with a cheap 304. */
function upx_send_file($file, $content_type, $status, $preview, $method) {
	$mtime = (int) filemtime($file);
	upx_send_headers($content_type, $status, $preview, '"' . md5($file . '|' . $mtime . '|' . filesize($file)) . '"', $mtime);
	if ($method !== 'HEAD') {
		readfile($file);
	}
	exit;
}

/** Sends generated HTML/XML/text (a built file with references added, or a reference page) and exits. */
function upx_send_body($body, $content_type, $status, $preview, $method, $mtime) {
	upx_send_headers($content_type, $status, $preview, '"' . md5($body) . '"', (int) $mtime);
	if ($method !== 'HEAD') {
		echo $body; // phpcs:ignore WordPress.Security.EscapeOutput -- built HTML filled with escaped values (refs-render.php)
	}
	exit;
}

/** Status and headers; answers a matching conditional request with 304 and exits. */
function upx_send_headers($content_type, $status, $preview, $etag, $mtime) {
	// Drop output buffers other plugins opened (Weglot translates language pages through one), so the file is sent as built.
	// Stops at a buffer PHP won't remove (e.g. zlib.output_compression) instead of looping on it.
	while (ob_get_level() > 0 && @ob_end_clean()) {
	}
	header('Content-Type: ' . $content_type);
	header('X-Unixpadel-Static: ' . ($preview ? 'preview' : 'live'));
	if (!$preview && $status === 200) {
		header('Cache-Control: public, max-age=300');
		header('Last-Modified: ' . gmdate('D, d M Y H:i:s', $mtime) . ' GMT');
		header('ETag: ' . $etag);
		$inm = isset($_SERVER['HTTP_IF_NONE_MATCH']) ? trim((string) $_SERVER['HTTP_IF_NONE_MATCH']) : '';
		$ims = isset($_SERVER['HTTP_IF_MODIFIED_SINCE']) ? strtotime((string) $_SERVER['HTTP_IF_MODIFIED_SINCE']) : false;
		if (($inm !== '' && $inm === $etag) || ($inm === '' && $ims !== false && $ims >= $mtime)) {
			status_header(304);
			exit;
		}
	}
	status_header($status);
	if ($status !== 200) {
		nocache_headers();
	}
}

/**
 * Misses (English and every language folder) get the new site's 404 page (noindex, new design) with a real 404 status, instead of the old
 * theme's. Language folders and WordPress paths keep WordPress's own 404.
 */
function upx_maybe_serve_404() {
	if (!is_404() || !upx_is_active_for_request()) {
		return;
	}
	$path = rawurldecode((string) parse_url(UPX_REQUEST_URI, PHP_URL_PATH));
	if (preg_match(UPX_PASS_PREFIX, $path)) {
		return;
	}
	$file = upx_404_file($path);
	if (is_file($file)) {
		$method = isset($_SERVER['REQUEST_METHOD']) ? strtoupper($_SERVER['REQUEST_METHOD']) : 'GET';
		upx_send_file($file, 'text/html; charset=utf-8', 404, upx_mode() !== 'live', $method);
	}
}
add_action('template_redirect', 'upx_maybe_serve_404', 0);

/** The new site's 404 page; misses under a language folder get that language's. */
function upx_404_file($path) {
	if (preg_match(UPX_LANG_PREFIX, $path, $m) && is_file(UPX_DIST . '/' . strtolower($m[1]) . '/404/index.html')) {
		return UPX_DIST . '/' . strtolower($m[1]) . '/404/index.html';
	}
	return UPX_DIST . '/404.html';
}

/** WordPress's "did you mean" 404 guessing would send old slugs to random new-site lookalikes. */
function upx_no_redirect_guess($guess) {
	return upx_is_active_for_request() ? false : $guess;
}
add_filter('do_redirect_guess_404_permalink', 'upx_no_redirect_guess');

/* ---------- Quote form (POST /?rest_route=/unixpadel/v1/quote, sent by src/components/QuoteForm.astro) ---------- */

define('UPX_OPT_QUOTE_TO', 'upx_quote_recipients'); // recipients of quote requests, comma separated
define('UPX_OPT_QUOTE_TO_LEGACY', 'upx_quote_to');   // single-address option of older builds; ignored, removed on uninstall
define('UPX_QUOTE_TO_DEFAULT', 'info@unixpadel.com, infotech@unixpadel.com');
define('UPX_QUOTE_POST_TYPE', 'upx_quote');       // every request is also saved here (WP admin → Quote requests)
define('UPX_QUOTE_MIN_MS', 3000);                 // a person needs longer than this to fill the form
define('UPX_QUOTE_MAX_PER_IP', 5);                // requests per IP address …
define('UPX_QUOTE_WINDOW', 10 * MINUTE_IN_SECONDS); // … per this window

/** Valid addresses from a comma/semicolon/space separated list, duplicates removed. */
function upx_parse_emails($value) {
	$emails = array();
	foreach (preg_split('/[\s,;]+/', (string) $value, -1, PREG_SPLIT_NO_EMPTY) as $email) {
		$email = sanitize_email($email);
		if (is_email($email)) {
			$emails[strtolower($email)] = $email;
		}
	}
	return array_values($emails);
}

/** @return string[] every address a quote request is mailed to */
function upx_quote_to() {
	$to = upx_parse_emails(get_option(UPX_OPT_QUOTE_TO, UPX_QUOTE_TO_DEFAULT));
	return $to ? $to : upx_parse_emails(UPX_QUOTE_TO_DEFAULT);
}

